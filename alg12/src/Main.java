    // heapsort dla fragmentu tablicy t: od indeksu od, dlugosc dl pomocnica do
    private static void heapsort(int[] t, int od, int dl) {
        for (int s = dl / 2 - 1; s >= 0; s--) przesun(t, od, dl, s);
        for (int k = dl - 1; k > 0; k--) {
            int x = t[od]; t[od] = t[od + k]; t[od + k] = x;
            przesun(t, od, k, 0);
        }
    }

    private static void przesun(int[] t, int od, int dl, int i) {
        while (true) {
            int max = i, l = 2 * i + 1, p = 2 * i + 2;
            if (l < dl && t[od + l] > t[od + max]) max = l;
            if (p < dl && t[od + p] > t[od + max]) max = p;
            if (max == i) break;
            int x = t[od + i]; t[od + i] = t[od + max]; t[od + max] = x;
            i = max;
        }
    }
